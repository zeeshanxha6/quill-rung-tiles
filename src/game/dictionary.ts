const SETS: Record<number, Set<string>> = {
  4: new Set(WORDS_4),
  5: new Set(WORDS_5),
  6: new Set(WORDS_6),
};

export function isValidWord(word: string): boolean {
  const set = SETS[word.length];
  return set ? set.has(word.toUpperCase()) : false;
}

export function wordsOfLength(length: number): string[] {
  const set = SETS[length];
  return set ? Array.from(set) : [];
}

/** A short, offline "definition" line for the word journal — no network lookup. */
export function describeWord(word: string): string {
  return `${word.length} LETTERS · RUNG WORD`;
}
